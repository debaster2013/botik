POPULAR_ZONES: dict[str, str] = {
    "com": "Международный коммерческий (самый популярный)",
    "net": "Сети, технологии и инфраструктура",
    "org": "Организации, сообщества и открытые проекты",
    "io": "Стартапы, IT, игры и инструменты",
    "dev": "Разработчики и проекты (требует HTTPS)",
    "app": "Приложения и веб-сервисы (требует HTTPS)",
    "ai": "Искусственный интеллект и ML-проекты",
    "gg": "Игровые проекты, киберспорт и комьюнити",
    "kz": "Национальная зона Казахстана",
    "ru": "Национальная зона России",
    "su": "Историческая доменная зона",
    "me": "Личные сайты, портфолио и визитки",
    "xyz": "Универсальная бюджетная зона",
    "store": "Магазины и товары",
}


def get_zone_info(zone: str) -> str:
    z = zone.lower().lstrip(".")
    desc = POPULAR_ZONES.get(z, "Пользовательская / не в базовом справочнике популярных зон")
    return f".{z} — {desc}"


def list_zones_text() -> str:
    lines = ["<b>Популярные доменные зоны:</b>"]
    for z, desc in POPULAR_ZONES.items():
        lines.append(f"• <code>.{z}</code> — {desc}")
    return "\n".join(lines)
